"""Parse and round-trip charts in all four Phimakor formats.

Covers the format-probing API: `detect_format_bytes` / `detect_format` and
`parse_chart_bytes` / `parse_chart` for PEC, PGR, PSS and PMK samples, plus
`RPEChart.to_pss` / `RPEChart.from_pss`, `Chart.hits_before` / `Chart.textures`
and `ChartInfo.from_info_txt`. Every assertion is structural (line/note counts,
BPM list, offset) so the script stays honest across format conventions.

Dependencies: only `phimakor` (built via `python -m maturin build --release`,
then `pip install target/wheels/phimakor-*.whl`). No GUI, no chart directory.

Run:
    python example/format_roundtrip.py
"""

